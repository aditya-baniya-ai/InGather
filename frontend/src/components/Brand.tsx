import { useId } from "react";
import { cx } from "./ui";

/** Three linked circles: separate people, one overlap. Our own mark, no borrowed glyph. */
export function LogoMark({ size = 28, className }: { size?: number; className?: string }) {
  const id = useId();
  return (
    <svg width={size} height={size} viewBox="0 0 32 32" className={className} aria-hidden>
      <defs>
        <linearGradient id={id} x1="0" y1="0" x2="1" y2="1">
          <stop offset="0" stopColor="#D94693" />
          <stop offset="1" stopColor="#7C57C2" />
        </linearGradient>
      </defs>
      <g fill="none" stroke={`url(#${id})`} strokeWidth="2.6">
        <circle cx="12" cy="12.5" r="6.5" />
        <circle cx="20" cy="12.5" r="6.5" />
        <circle cx="16" cy="19.5" r="6.5" />
      </g>
    </svg>
  );
}

export function Wordmark({ className, mark = true }: { className?: string; mark?: boolean }) {
  return (
    <span className={cx("inline-flex items-center gap-2 font-semibold tracking-[-0.03em] text-ink", className)}>
      {mark && <LogoMark />}
      <span className="text-[24px] leading-none">ingather<span className="text-rose">.</span></span>
    </span>
  );
}

const CITY_PHOTOS = new Set(["philadelphia", "austin"]);
const ACTIVITY_PHOTOS = new Set(["conference", "travel", "hackathon", "study", "coffee", "event", "other"]);

/** Photo for a plan: its own Muse Image cover, else the city photo, else the activity photo (all generated by Muse Image). */
export function coverSrc(activity: string, city?: string | null, src?: string | null) {
  const slug = city?.trim().toLowerCase();
  if (src) return src;
  if (slug && CITY_PHOTOS.has(slug)) return `/images/city-${slug}.jpg`;
  return `/images/${ACTIVITY_PHOTOS.has(activity) ? activity : "other"}.jpg`;
}

export function Cover({ activity, city, src, className, label }: { activity: string; city?: string | null; src?: string | null; className?: string; label?: string }) {
  return <img src={coverSrc(activity, city, src)} alt={label ?? ""} loading="lazy" decoding="async" className={cx("bg-line object-cover", className)} />;
}
